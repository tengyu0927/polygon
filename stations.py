"""stations.py — 站点清单的**唯一真相源**。

    import stations as S
    S.ICAOS          # ['ZBAA', 'ZGGG', ...]  排序固定
    S.NAMES["ZBAA"]  # '北京首都'
    S.COORD["ZBAA"]  # (40.0801, 116.5846)
    S.CSV            # 'ZBAA,ZGGG,...'  给 shell 用

为什么要这个文件:

2026-08-08 加郑州/济南之前清点，发现站点清单硬编码在 **17 个文件**里，
三种形式（ICAO->经纬度 7 处、ICAO->中文名 7 处、逗号串 3 处）。这类重复
已经出过两次事故:
  - ZGSZ 因 --split-year 静默从模型里掉出去，检查还是绿的
  - stn_id 训练端设了、预测端没设，靠逐列比对才抓到
而且清点时当场又发现一处**活着的不一致**: 青岛的经度在 build_mos_dataset.py
里是 120.0864（胶东机场，正确），在另外 6 个取模式数据的文件里是 120.3864 ——
差 0.3 度约 27 公里，在 0.25 度网格上是**不同格点**。也就是 Open-Meteo 六模式
取的是胶东，本地 GFS 取的是别处。120.3864 既不是胶东也不是流亭（120.3744），
像是 0864 打成 3864。流亭 2021 年已关闭，胶东才是在运行的机场。

**本文件一律用正确坐标。** 但本地 GFS 的历史归档（gfs18.csv / mos_local*.csv）
是按旧坐标抽的，直接改会让训练/预测口径错位，所以给了 LEGACY_GFS_COORD ——
在重新抽取并 A/B 验证之前，取 GFS 的那几个脚本仍用旧值。
"""

from __future__ import annotations

# ICAO -> (中文名, 纬度, 经度)
# 坐标以机场基准点为准，用于取数值模式的最近格点。
_STATIONS = {
    "ZBAA": ("北京首都", 40.0801, 116.5846),
    "ZSPD": ("上海浦东", 31.1443, 121.8083),
    "ZGGG": ("广州白云", 23.3924, 113.2988),
    "ZGSZ": ("深圳宝安", 22.6393, 113.8107),
    "ZUUU": ("成都双流", 30.5785, 103.9471),
    "ZUCK": ("重庆江北", 29.7192, 106.6417),
    "ZHHH": ("武汉天河", 30.7838, 114.2081),
    "ZSQD": ("青岛胶东", 36.3661, 120.0864),
    # 2026-08-08 新增。实况来源不同:
    #   ZHCC 郑州: IEM 有 1995 年起的逐时（720 条/月），与原 8 站同源
    #   ZSJN 济南: IEM 只有 42-81 条/月（每天 1-2 条，不是逐时），**不可用**，
    #              必须走 WU（2020 年起逐时齐全），与 ZGSZ 同一条路
    "ZHCC": ("郑州新郑", 34.5197, 113.8408),
    "ZSJN": ("济南遥墙", 36.8572, 117.2160),
}

# 本地 GFS 抽取用的旧坐标。**2026-08-24 已清空 —— A/B 做完了，切换完成。**
#
# 当初的判断是「120.3864 是 120.0864 打错了」，那不对: 那个点离**流亭**
# 只有 10.7 km、离胶东 26.9 km，是照着流亭抄的，不是笔误。而且它多半落在
# 胶州湾水面上 —— ERA5 在该点取的日最高温对 ZSQD 实测有 **-2.75℃** 的冷偏差。
#
# 三个候选点用 ERA5 对 ZSQD 实测（475 天）:
#     胶东 stations.COORD    MAE 0.841   ME +0.16   r 0.9940   <- 最好
#     LEGACY（原用）          MAE 2.957   ME -2.75   r 0.9749   <- 最差
#     流亭（结算源元数据）      MAE 1.678   ME -1.40   r 0.9894
# **ZSQD 的实测行为像胶东，不像流亭** —— 站确实搬了（2021-08-12），结算源
# 元数据里那个 "Liuting Airport" 是陈旧信息。搬站前后序列也没有台阶
# （前 1 年 -1.41 / 后 1 年 -1.65，而标准差 2.5+）。
#
# 本地 GFS 归档的实测 A/B（875 天，18Z 那份）:
#     ZSQD（LEGACY 点）    MAE 1.459   ME -0.846
#     ZSQD_NEW（胶东）      MAE 1.251   ME -0.061   -> MAE 改善 14.2%
# 归档已按 ZSQD_NEW 重写（旧 ZSQD 行丢弃、ZSQD_NEW 改名 ZSQD），
# mos_local12/6.csv 也已重建。
LEGACY_GFS_COORD = {}

ICAOS = sorted(_STATIONS)
NAMES = {k: v[0] for k, v in _STATIONS.items()}
COORD = {k: (v[1], v[2]) for k, v in _STATIONS.items()}
CSV = ",".join(ICAOS)

# 实况以 Weather Underground 为准、不能用 AWC/IEM METAR 的站。
#
# **2026-08-24: ZGSZ 移出。** 结算源换成了 weather.gov 的 WRH timeseries
# （背后是 Synoptic/MesoWest，供的就是 METAR 原文），十个站里九个都改了，
# 只有济南还是 WU。逐条核对过去 24 小时: 八个 IEM 站与新结算源**100% 相同**
# （同一条 METAR 馈送），唯独深圳不同 —— 因为 WU 的 ZGSZ:9:CN 挂的是
# **香港流浮山**（WMO 45035），而新结算源的 ZGSZ 是真的深圳宝安
# （22.6393, 113.8110，与本文件坐标一致）。
#
# 两条序列的日最高温只有 29.4% 的日子相同、MAE 1.06℃（469 天可比）——
# 也就是说此前深圳有七成日子在预报另一个地方。已用 wu_obs.py --restore
# 把 obs_zgsz_metar 里备份的真实 METAR 换回来（259,092 条，1995 年起），
# 顺带把这个站的可用历史从 2 年扩到 31 年。
#
#   ZSJN: IEM 根本没有逐时数据（42-81 条/月），只能用 WU
WU_STATIONS = {"ZSJN"}


def gfs_coord(icao):
    """取 GFS 抽取用的坐标（含历史遗留覆盖）。"""
    return LEGACY_GFS_COORD.get(icao, COORD[icao])


GFS_COORD = {k: gfs_coord(k) for k in ICAOS}

# 抽取时额外多抽的点。2026-08-08 为青岛的坐标之争加了 ZSQD_NEW（胶东正确
# 坐标），**2026-08-24 A/B 做完、已切换，所以清空** —— 现在 GFS_COORD["ZSQD"]
# 本身就是胶东，再多抽一份只会得到重复的列。
# 以后再遇到「怀疑某站坐标不对」，照这个套路走: 先加进来多抽一份（同一份
# GRIB 缓冲，成本≈0），攒够天数用实测 A/B 判，赢了再切。
EXTRA_POINTS = {}
GFS_COORD_EXTRACT = {**GFS_COORD, **EXTRA_POINTS}
